#[derive(Clone, Copy)]
pub struct TextStyle<'a> {
    pub font: Font,
    pub size: f64,
    pub color: &'a str,
    pub width: Option<f64>,
    pub align: Align,
    pub line_gap: f64,
}

impl<'a> TextStyle<'a> {
    pub fn new(size: f64, color: &'a str) -> Self {
        Self {
            font: Font::Regular,
            size,
            color,
            width: None,
            align: Align::Left,
            line_gap: 0.0,
        }
    }
    pub fn bold(mut self) -> Self {
        self.font = Font::Bold;
        self
    }
    pub fn width(mut self, w: f64, align: Align) -> Self {
        self.width = Some(w);
        self.align = align;
        self
    }
    pub fn gap(mut self, g: f64) -> Self {
        self.line_gap = g;
        self
    }
}

