    /// `drawFooters`: footer di setiap halaman; panggil sekali, tepat sebelum `finish`.
    pub fn draw_footers(&mut self, o: &FooterOptions<'_>) {
        let count = self.doc.page_count();
        let company = or_company(o.company_name, o.company_fallback);
        let confidential = o.confidential_label.unwrap_or("Confidential");
        let generated_by = o
            .generated_by_label
            .unwrap_or("Generated by Timemoz \u{b7} www.timemoz.com");
        let extra = o
            .extra_line
            .map(|e| clean_text(Some(e)))
            .unwrap_or_default();
        let extra_h = if extra.is_empty() {
            0.0
        } else {
            height_of(&extra, CW, Font::Regular, 7.0, 0.0) + 3.0
        };
        for i in 0..count {
            let fy = PAGE_H - 42.0 - extra_h;
            self.doc.line_on(i, M, fy, PAGE_W - M, fy, 0.6, BORDER);
            let left = fit(
                &format!(
                    "{company}  \u{b7}  {}  \u{b7}  {confidential}",
                    o.report_title
                ),
                CW - 120.0,
                Font::Regular,
                7.0,
            );
            self.doc
                .text_at(Some(i), &left, M, fy + 10.0, Font::Regular, 7.0, FAINT);
            if !extra.is_empty() {
                let lh = line_height(7.0);
                for (n, line) in wrap(&extra, CW, Font::Regular, 7.0).iter().enumerate() {
                    #[allow(clippy::cast_precision_loss)]
                    let ly = fy + 20.0 + lh * n as f64;
                    self.doc
                        .text_at(Some(i), line, M, ly, Font::Regular, 7.0, FAINT);
                }
            }
            self.doc.text_at(
                Some(i),
                generated_by,
                M,
                fy + 20.0 + extra_h,
                Font::Regular,
                7.0,
                FAINT,
            );
            let page = match o.page_label {
                Some(f) => f(i + 1, count),
                None => format!("Page {} of {count}", i + 1),
            };
            let x = PAGE_W - M - text_width(&page, Font::Bold, 7.5);
            self.doc
                .text_at(Some(i), &page, x, fy + 10.0, Font::Bold, 7.5, MUTED);
        }
    }
